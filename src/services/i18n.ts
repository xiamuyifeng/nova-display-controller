const storedLocale = typeof localStorage === "undefined" ? null : localStorage.getItem("nova-app-locale");
export const appLocale = ref<AppLocale>(storedLocale === "en-US" ? "en-US" : "zh-CN");

export function formatTranslation(source: string, locale: AppLocale, params: Params = {}) {
  const template = locale === "en-US" ? en[source] ?? source : source;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (token, key: string) => String(params[key] ?? token));
}

export function translate(source: string, params: Params = {}) {
  return formatTranslation(source, appLocale.value, params);
}

export function setLocale(locale: AppLocale) {
  appLocale.value = locale;
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  if (typeof localStorage !== "undefined") localStorage.setItem("nova-app-locale", locale);
}

export function useI18n() {
  return { locale: appLocale, setLocale, t: translate };
}

setLocale(appLocale.value);
